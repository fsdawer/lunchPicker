CREATE TABLE IF NOT EXISTS lunchpicker.community_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL REFERENCES lunchpicker.users (id),
    body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
    area_location public.geography(POINT, 4326) NOT NULL,
    restaurant_id BIGINT REFERENCES lunchpicker.restaurants (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS community_posts_area_gix ON lunchpicker.community_posts USING GIST (area_location);
CREATE INDEX IF NOT EXISTS community_posts_created_idx ON lunchpicker.community_posts (created_at DESC, id DESC);
