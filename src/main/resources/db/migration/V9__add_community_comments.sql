ALTER TABLE lunchpicker.community_posts
    ADD COLUMN view_count BIGINT NOT NULL DEFAULT 0;

CREATE TABLE lunchpicker.post_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES lunchpicker.community_posts (id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES lunchpicker.users (id),
    body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX post_comments_post_created_idx
    ON lunchpicker.post_comments (post_id, created_at DESC, id DESC);
