ALTER TABLE lunchpicker.users ADD COLUMN email VARCHAR(254) UNIQUE;
ALTER TABLE lunchpicker.users ADD COLUMN password_hash VARCHAR(100);

CREATE TABLE lunchpicker.login_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES lunchpicker.users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX login_sessions_user_idx ON lunchpicker.login_sessions (user_id);
