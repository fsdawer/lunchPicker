CREATE TABLE lunchpicker.restaurant_favorites (
    user_id BIGINT NOT NULL REFERENCES lunchpicker.users (id) ON DELETE CASCADE,
    restaurant_id BIGINT NOT NULL REFERENCES lunchpicker.restaurants (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, restaurant_id)
);
CREATE INDEX restaurant_favorites_restaurant_idx ON lunchpicker.restaurant_favorites (restaurant_id);

CREATE TABLE lunchpicker.restaurant_detail_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES lunchpicker.restaurants (id) ON DELETE CASCADE,
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX restaurant_detail_views_restaurant_time_idx
    ON lunchpicker.restaurant_detail_views (restaurant_id, viewed_at DESC);
