CREATE TABLE lunchpicker.meetup_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meetup_id BIGINT NOT NULL REFERENCES lunchpicker.meal_meetups (id),
    sender_id BIGINT NOT NULL REFERENCES lunchpicker.users (id),
    body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX meetup_messages_meetup_id_idx ON lunchpicker.meetup_messages (meetup_id, id);
