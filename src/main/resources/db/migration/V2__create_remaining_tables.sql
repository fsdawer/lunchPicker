CREATE TABLE lunchpicker.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE lunchpicker.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES lunchpicker.restaurants (id),
    author_id BIGINT NOT NULL REFERENCES lunchpicker.users (id),
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX reviews_restaurant_created_idx
    ON lunchpicker.reviews (restaurant_id, created_at DESC, id DESC);
CREATE INDEX reviews_author_idx ON lunchpicker.reviews (author_id);

CREATE TABLE lunchpicker.menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES lunchpicker.restaurants (id),
    name VARCHAR(100) NOT NULL,
    price_krw INTEGER CHECK (price_krw >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX menus_restaurant_idx ON lunchpicker.menus (restaurant_id);

CREATE TABLE lunchpicker.companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    location public.geography(POINT, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX companies_location_gix ON lunchpicker.companies USING GIST (location);

CREATE TABLE lunchpicker.company_memberships (
    user_id BIGINT NOT NULL REFERENCES lunchpicker.users (id),
    company_id BIGINT NOT NULL REFERENCES lunchpicker.companies (id),
    verification_status VARCHAR(20) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, company_id)
);

CREATE INDEX company_memberships_company_idx ON lunchpicker.company_memberships (company_id);

CREATE TABLE lunchpicker.meal_meetups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_user_id BIGINT NOT NULL REFERENCES lunchpicker.users (id),
    restaurant_id BIGINT NOT NULL REFERENCES lunchpicker.restaurants (id),
    starts_at TIMESTAMPTZ NOT NULL,
    capacity SMALLINT NOT NULL CHECK (capacity >= 2),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX meal_meetups_host_idx ON lunchpicker.meal_meetups (host_user_id);
CREATE INDEX meal_meetups_restaurant_idx ON lunchpicker.meal_meetups (restaurant_id);

CREATE TABLE lunchpicker.meal_meetup_members (
    meetup_id BIGINT NOT NULL REFERENCES lunchpicker.meal_meetups (id),
    user_id BIGINT NOT NULL REFERENCES lunchpicker.users (id),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (meetup_id, user_id)
);

CREATE INDEX meal_meetup_members_user_idx ON lunchpicker.meal_meetup_members (user_id);
